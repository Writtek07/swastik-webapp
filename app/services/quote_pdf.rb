# Renders a QuoteCalculator::Quote as an A4 quotation PDF, laid out like the
# printed gauge difference sheets: a company header, coloured title bands, the
# priced line, a totals block and the standard notes.
#
#   QuotePdf.new(quote).render  # => PDF bytes
#
# Prawn's built-in Helvetica has no ₹ glyph, so amounts are written "Rs.".
class QuotePdf
  EMBER  = "F95711"
  EMBER_DARK = "C22B08"
  CREAM  = "FFF5ED"
  PEACH  = "FFCDA8"
  YELLOW = "FFE45C"
  INK    = "141922"
  MUTED  = "667085"
  RULE   = "B3BAC7"
  RED    = "C22B08"

  ROW = 22
  HEADER_HEIGHT = 108

  # Horizontal logo (mark + wordmark), generated by script/brand/build. A PNG
  # because Prawn can't embed the WebP files the site uses.
  LOGO = Rails.root.join("app/assets/images/brand/lockup-light.png")
  LOGO_HEIGHT = 36

  def initialize(quote, company: Catalog::COMPANY, gstn: Setting.current.gstn)
    @quote = quote
    @company = company
    @gstn = gstn
  end

  def render
    Prawn::Document.new(page_size: "A4", margin: 32, info: { Title: "Quotation #{@quote.number}", Creator: @company[:name] }) do |pdf|
      @pdf = pdf
      pdf.font "Helvetica"
      pdf.default_leading 1
      header
      band(EMBER, "W.E.F. #{date(@quote.basic_priced_on)}  ·  GAUGE SESSION #{@quote.guage_session.label}", color: "FFFFFF")
      band(YELLOW, "PRICE QUOTATION — #{@quote.product.title.upcase}", color: EMBER_DARK, size: 12)
      pdf.move_down 14
      line_items
      pdf.move_down 14
      totals
      pdf.move_down 18
      notes
      footer
      pdf.stroke_color RULE
      pdf.stroke_bounds
    end.render
  end

  private

  attr_reader :pdf

  def header
    top = pdf.cursor
    pdf.fill_color CREAM
    pdf.fill_rectangle [ 0, top ], pdf.bounds.width, HEADER_HEIGHT
    pdf.fill_color INK

    pdf.bounding_box([ 14, top - 12 ], width: pdf.bounds.width * 0.62) do
      logo
      pdf.move_down 6
      pdf.text @company[:legal_name], size: 9, color: MUTED
      pdf.move_down 6
      pdf.text @company[:address], size: 9
      pdf.text "PH: #{[ @company[:phone], @company[:phone_alt] ].compact.join(', ')}  ·  #{@company[:email]}", size: 9
      pdf.text "GSTIN: #{@gstn}", size: 9, style: :bold if @gstn.present?
    end

    right = pdf.bounds.width * 0.66
    pdf.bounding_box([ right, top - 12 ], width: pdf.bounds.width - right - 14) do
      pdf.text "QUOTATION", size: 18, style: :bold, align: :right, color: INK
      pdf.move_down 4
      pdf.text "No. #{@quote.number}", size: 9, align: :right
      pdf.text "Date: #{date(@quote.quoted_on)}", size: 9, align: :right
    end

    pdf.move_cursor_to top - HEADER_HEIGHT
  end

  # Falls back to the name in type if the logo file is missing, so a quotation
  # still renders.
  def logo
    if LOGO.exist?
      pdf.image LOGO.to_s, height: LOGO_HEIGHT
    else
      pdf.text @company[:name].upcase, size: 22, style: :bold, color: EMBER
    end
  end

  def band(fill, label, color:, size: 11)
    top = pdf.cursor
    pdf.fill_color fill
    pdf.fill_rectangle [ 0, top ], pdf.bounds.width, ROW
    pdf.fill_color color
    pdf.text_box label, at: [ 0, top ], width: pdf.bounds.width, height: ROW, size: size, style: :bold,
                        align: :center, valign: :center
    pdf.fill_color INK
    pdf.move_cursor_to top - ROW
  end

  LINE_COLUMNS = [ [ "PRODUCT", 0.22, :left ], [ "SIZE", 0.12, :center ], [ "QTY (MT)", 0.1, :center ],
                   [ "BASIC RATE", 0.15, :right ], [ "GAUGE DIFF", 0.11, :right ], [ "RATE", 0.15, :right ],
                   [ "AMOUNT", 0.15, :right ] ].freeze

  def line_items
    pdf.indent(14, 14) do
      widths = LINE_COLUMNS.map { |(_, share, _)| pdf.bounds.width * share }
      aligns = LINE_COLUMNS.map(&:last)
      row(LINE_COLUMNS.map(&:first), widths, aligns, fill: PEACH, bold: true)
      row([ @quote.product.title, @quote.size, quantity, money(@quote.basic_price), number(@quote.guage_diff),
            money(@quote.rate), money(@quote.amount) ], widths, aligns)
      pdf.move_down 6
      pdf.text "Rate = basic rate #{money(@quote.basic_price)} (#{date(@quote.basic_priced_on)}) + gauge difference " \
               "#{number(@quote.guage_diff)} for #{@quote.size}.", size: 8, color: MUTED
    end
  end

  def totals
    lines = [
      [ "Amount", money(@quote.amount) ],
      [ "Loading charges", money(@quote.loading_charges) ],
      [ "Taxable value", money(@quote.taxable) ],
      [ "GST @ #{number(@quote.gst_percent)}%", money(@quote.gst) ]
    ]
    width = 240
    pdf.indent(pdf.bounds.width - width - 14, 14) do
      widths = [ width * 0.55, width * 0.45 ]
      lines.each { |cells| row(cells, widths, %i[left right]) }
      row([ "GRAND TOTAL", money(@quote.total) ], widths, %i[left right], fill: EMBER, bold: true, color: "FFFFFF")
    end
  end

  def notes
    band(EMBER, "NOTE", color: "FFFFFF")
    pdf.move_down 8
    pdf.indent(14, 14) do
      [
        "Basic rate as published on #{date(@quote.basic_priced_on)}. Rates change daily; this quotation is valid for the date issued only.",
        "Gauge difference per the #{@quote.guage_session.label} gauge session (#{@quote.guage_session.date_range}).",
        "Loading charges are applied once per quotation. GST at #{number(@quote.gst_percent)}% on the taxable value.",
        "Indicative quotation generated online. Final pricing is confirmed on the sales order."
      ].each_with_index do |note, index|
        pdf.text "#{index + 1}. #{note}", size: 9, leading: 2
      end
    end
  end

  def footer
    pdf.move_cursor_to 34
    pdf.stroke_color RULE
    pdf.stroke_horizontal_rule
    pdf.move_down 10
    pdf.text "***THANK YOU FOR YOUR BUSINESS!!***", size: 11, style: :bold, color: RED, align: :center
  end

  def row(cells, widths, aligns, fill: nil, bold: false, color: INK)
    top = pdf.cursor
    x = 0
    cells.each_with_index do |cell, index|
      if fill
        pdf.fill_color fill
        pdf.fill_rectangle [ x, top ], widths[index], ROW
      end
      pdf.stroke_color RULE
      pdf.stroke_rectangle [ x, top ], widths[index], ROW
      pdf.fill_color color
      pdf.text_box cell.to_s, at: [ x + 6, top ], width: widths[index] - 12, height: ROW, size: 9,
                              style: bold ? :bold : :normal, align: aligns[index], valign: :center, overflow: :shrink_to_fit
      x += widths[index]
    end
    pdf.fill_color INK
    pdf.move_cursor_to top - ROW
  end

  # Indian digit grouping: 12,34,567.00
  INDIAN_GROUPS = /(\d+?)(?=(\d\d)+(\d)(?!\d))/

  def money(value)
    "Rs. #{ActiveSupport::NumberHelper.number_to_delimited(format('%.2f', value), delimiter_pattern: INDIAN_GROUPS)}"
  end

  def number(value)
    ActiveSupport::NumberHelper.number_to_rounded(value, precision: 2, strip_insignificant_zeros: true)
  end

  def quantity
    number(@quote.quantity)
  end

  def date(value)
    value.strftime("%d/%b/%Y").upcase
  end
end
